class Generated(unittest.TestCase):
    def test_every_allowed_step_makes_a_script_with_one_load_and_one_run(self):
        count = 0
        for slbounce, (app, vectors) in product(autorun.SLBOUNCE_BUILDS, autorun.APP_ARGUMENTS.items()):
            for args in vectors:
                with self.subTest(slbounce=slbounce, app=app, args=args):
                    plan = autorun.build_plan('p', [' '.join((slbounce, app) + args)], {slbounce: 'a' * 64, app: 'b' * 64})
                    script = autorun.render_script(plan).decode('ascii')
                    lines = script.split('\r\n')
                    self.assertEqual([l for l in lines if l.startswith('load ')], [f'load SP11\\{slbounce}'])
                    self.assertEqual([l for l in lines if l.startswith('SP11\\')], [' '.join((f'SP11\\{app}',) + args)])
                    self.assertEqual(autorun.script_problems(script), [])
                    count += 1
        self.assertEqual(count, 4 * 5)

    def test_plans_of_every_length(self):
        for n in range(1, 9):
            steps = [f'{autorun.SLBOUNCE_BUILDS[k % 4]} {("Q1N1.EFI --el2", "TESTS.EFI", "PROBE.EFI")[k % 3]}' for k in range(n)]
            used = {w for s in steps for w in s.split()[:2]}
            plan = autorun.build_plan('n', steps, {w: 'a' * 64 for w in used})
            script = autorun.render_script(plan).decode('ascii')
            self.assertEqual(script.count('\r\nload '), n)
            self.assertEqual(script.count(' >a SP11\\DONE'), n)
            self.assertEqual(script.count('\r\nstall '), n)
            self.assertEqual(autorun.parse_plan_text(autorun.render_plan_text(plan)), plan)

    def test_the_marker_names_are_8_3_and_distinct(self):
        names = [autorun.MARKER_FORMAT.format(k) for k in range(1, 9)]
        self.assertEqual(len(set(names)), 8)
        for name in names:
            base, _, ext = name.partition('.')
            self.assertTrue(len(base) <= 8 and len(ext) <= 3 and autorun.MARKER_RE.fullmatch(name))


class Behaviour(unittest.TestCase):
    """The control flow of the generated script, over every marker state."""

    def run_plan(self, steps, markers=(), files=None, writable=True):
        plan = plan_of(steps)
        names = set(plan.files()) if files is None else files
        return plan, simulate(autorun.render_script(plan).decode('ascii'), names, markers, writable)

    def test_step_k_runs_only_if_its_marker_is_absent_and_every_lower_marker_is_present(self):
        for steps in (ONE, TWO, TWO + ['SLBOUNCE-DRYRUN.EFI TESTS.EFI'],
                      TWO + ['SLBOUNCE.EFI PROBE.EFI', 'SLBOUNCE-DRYRUN.EFI Q1N1.EFI']):
            n = len(steps)
            for state in product((False, True), repeat=n):
                present = {k for k, has in enumerate(state, 1) if has}
                plan, ran = self.run_plan(steps, present)
                runnable = [k for k in range(1, n + 1) if k not in present and all(j in present for j in range(1, k))]
                with self.subTest(steps=n, present=sorted(present)):
                    if runnable:
                        (k,) = runnable
                        step = plan.steps[k - 1]
                        self.assertEqual(ran.loaded, [f'SP11\\{step.slbounce}'])
                        self.assertEqual(ran.ran, [f'SP11\\{step.run_line}'])
                        self.assertEqual(ran.written, [f'SP11\\DONE{k}.TXT'])
                    else:
                        self.assertEqual((ran.loaded, ran.ran, ran.written), ([], [], []))
                        self.assertIn('ALL STEPS DONE, run --clear to repeat', ran.said)
                    self.assertLessEqual(len(ran.loaded), 1, 'slbounce is loaded at most once per boot')

    def test_a_missing_file_refuses_before_anything_is_written_or_run(self):
        plan = plan_of()
        for markers in ((), (1,)):
            step = plan.steps[len(markers)]
            for missing in (step.slbounce, step.app):
                with self.subTest(missing=missing, markers=markers):
                    _, ran = self.run_plan(TWO, markers, files=set(plan.files()) - {missing})
                    self.assertEqual((ran.loaded, ran.ran, ran.written), ([], [], []))
                    self.assertIn(f'AUTORUN REFUSED: SP11\\{missing} is missing, nothing was run', ran.said)

    def test_a_marker_that_cannot_be_written_stops_the_step(self):
        _, ran = self.run_plan(TWO, writable=False)
        self.assertEqual((ran.loaded, ran.ran), ([], []))
        self.assertIn('AUTORUN REFUSED: cannot write SP11\\DONE1.TXT, nothing was run', ran.said)

    def test_the_model_would_notice_a_script_that_runs_two_steps(self):
        broken = GOLDEN_TWO.replace('SP11\\Q1N1.EFI --el2\r\ngoto end\r\n:step2', 'SP11\\Q1N1.EFI --el2\r\n:step2', 1)
        self.assertEqual(len(simulate(broken, set(plan_of().files())).loaded), 2)
        self.assertNotEqual(autorun.script_problems(broken), [])


class PlanText(unittest.TestCase):
    def test_round_trip(self):
        for steps, name in ((TWO, 'devhe-mark'), (ONE, 'run-a')):
            plan = plan_of(steps, name)
            self.assertEqual(autorun.parse_plan_text(autorun.render_plan_text(plan)), plan)

    def test_every_change_that_the_plan_model_cannot_hold_is_refused(self):
        good = GOLDEN_PLAN_TWO
        cases = {
            'hash uppercase': good.replace('a' * 64, 'A' * 64, 1),
            'banned argument': good.replace('Q1N1.EFI --el2', 'Q1N1.EFI --boot', 1),
            'extra argument': good.replace('Q1N1.EFI --el2', 'Q1N1.EFI --el2 --uart', 1),
            'scratch build': good.replace('SLBOUNCE-DEVHE.EFI', 'SLBOUNCE-OLD-NOSWEEP.EFI', 1),
            'name outside the tables': good.replace('Q1N1.EFI --el2', 'SLTEST.EFI', 1),
            'step count': good.replace('steps: 2', 'steps: 1', 1),
            'step order': good.replace('step 1\r\n', 'step 3\r\n', 1),
            'marker number': good.replace('DONE1.TXT, written', 'DONE5.TXT, written', 1),
            'prose': good.replace('How it runs', 'How it works', 1),
            'extra line': good + 'echo hi\r\n',
            'truncated': good[:-40],
            'lf only': good.replace('\r\n', '\n'),
            'empty': '',
            'two hashes for one file': good.replace('c' * 64, 'e' * 64, 1),
        }
        for what, text in cases.items():
            with self.subTest(what):
                with self.assertRaises(autorun.PlanError):
                    autorun.parse_plan_text(text.encode('ascii'))
        with self.assertRaises(autorun.PlanError):
            autorun.parse_plan_text('caf\u00e9'.encode('utf-8'))

    def test_the_reasons(self):
        def reason(text):
            return reason_of(autorun.parse_plan_text, text.encode('ascii'))
        self.assertEqual(reason(GOLDEN_PLAN_TWO.replace('Q1N1.EFI --el2', 'Q1N1.EFI --boot', 1)), 'step_argument_banned')
        self.assertEqual(reason(GOLDEN_PLAN_TWO.replace('How it runs', 'How it works', 1)), 'plan_text_not_canonical')
        self.assertEqual(reason(GOLDEN_PLAN_TWO.replace('c' * 64, 'e' * 64, 1)), 'plan_inconsistent_hash')
        self.assertEqual(reason(''), 'plan_text_unparseable')

    def test_a_changed_name_or_hash_is_a_valid_plan_of_its_own(self):
        # Parsing says what the file claims; verify compares that claim with the script and the staged files.
        other = autorun.parse_plan_text(GOLDEN_PLAN_TWO.replace('plan: devhe-mark', 'plan: other', 1).encode('ascii'))
        self.assertEqual(other.name, 'other')
        self.assertNotEqual(autorun.render_script(other), autorun.render_script(plan_of()))


