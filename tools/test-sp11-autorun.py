class Ran:
    def __init__(self):
        self.loaded, self.ran, self.said, self.written = [], [], [], []


def simulate(script, files, markers=(), writable=True):
    """Runs `script` as the Shell would, for its control flow only: SP11\\<name> is present for each name in `files`,
    for SP11\\PLAN.TXT and for each marker numbered in `markers`. Only echo, if exist / endif, goto, labels, stall, the
    marker redirect, load and a command line are modelled (as tools/test-sp11-autorun-qemu.py saw them behave under the
    pinned Shell); anything else raises."""
    lines = [line.strip() for line in script.split('\r\n') if line and not line.startswith('#')]
    labels = {line[1:]: index for index, line in enumerate(lines) if line.startswith(':')}
    present = {f'SP11\\{name}' for name in files} | {'SP11\\PLAN.TXT'} | {f'SP11\\DONE{k}.TXT' for k in markers}
    out, index = Ran(), 0
    while index < len(lines):
        line = lines[index]
        index += 1
        if line.startswith((':', '@echo', '%homefilesystem%', 'stall ')) or line == 'endif':
            continue
        found = re.fullmatch(r'echo "(.*)" >a (SP11\\DONE\d\.TXT)', line)
        if found:
            if writable:
                present.add(found.group(2))
            out.written.append(found.group(2))
        elif line.startswith('echo "'):
            out.said.append(line[6:-1])
        elif line.startswith('if '):
            found = re.fullmatch(r'if (not )?exist (\S+) then', line)
            if (found.group(2) in present) == bool(found.group(1)):
                index = lines.index('endif', index) + 1
        elif line.startswith('goto '):
            index = labels[line[5:]]
        elif line.startswith('load '):
            out.loaded.append(line[5:])
        elif line.startswith('SP11\\'):
            out.ran.append(line)
        else:
            raise AssertionError(f'the model does not know {line!r}')
    return out


def reason_of(call, *args):
    try:
        call(*args)
    except autorun.PlanError as error:
        return error.reason
    raise AssertionError('no PlanError')


class GoldenText(unittest.TestCase):
    def test_the_two_step_script(self):
        self.assertEqual(autorun.render_script(plan_of()).decode('ascii'), GOLDEN_TWO)

    def test_the_one_step_script(self):
        self.assertEqual(autorun.render_script(plan_of(ONE, 'run-a')).decode('ascii'), GOLDEN_ONE)

    def test_plan_text(self):
        self.assertEqual(autorun.render_plan_text(plan_of()).decode('ascii'), GOLDEN_PLAN_TWO)

    def test_the_autorun_paragraph_replaces_the_manual_one_and_only_that(self):
        base = stage.build_readme_text()
        changed = autorun.readme_for_plan(base, plan_of())
        self.assertEqual(changed, base.replace(autorun.README_MANUAL_PARAGRAPH, GOLDEN_README_PARAGRAPH))
        self.assertNotIn('No startup.nsh file is present', changed)
        changed.encode('ascii')
        self.assertEqual(reason_of(autorun.readme_for_plan, 'no such paragraph', plan_of()), 'readme_paragraph_missing')
        self.assertEqual(reason_of(autorun.readme_for_plan, base + autorun.README_MANUAL_PARAGRAPH, plan_of()),
                         'readme_paragraph_missing')

    def test_scripts_are_small_plain_ascii_with_crlf_endings(self):
        for steps in (ONE, TWO):
            text = autorun.render_script(plan_of(steps, 'x')).decode('ascii')
            lines = text.split('\r\n')
            self.assertEqual(lines.pop(), '', 'ends with a line break')
            self.assertLessEqual(len(lines), 14 + 25 * len(steps))
            self.assertTrue(all(len(line) <= 100 and line.isprintable() and line == line.rstrip() for line in lines))
            self.assertNotIn('\n', text.replace('\r\n', ''))


