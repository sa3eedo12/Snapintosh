class PlanTextWithData(unittest.TestCase):
    def reason(self, text):
        return reason_of(autorun.parse_plan_text, text.encode('ascii'))

    def test_a_size_or_hash_the_text_changes_is_a_plan_of_its_own_that_verify_compares_with_the_staged_bytes(self):
        original = autorun.parse_plan_text(GOLDEN_PLAN_ONE.encode('ascii'))
        for old, new in (('size 1024', 'size 1025'), ('785b0751', '785b0752')):
            other = autorun.parse_plan_text(GOLDEN_PLAN_ONE.replace(old, new).encode('ascii'))
            self.assertNotEqual(other, original)

    def test_text_the_tool_would_not_write_is_refused_for_the_reason_of_the_rule_it_breaks(self):
        good = GOLDEN_PLAN_ONE
        cases = {
            'data_manifest_missing': good.replace(DATA_ONE, ''),
            'data_name_invalid': good.replace('file STATE.BIN', 'file state.bin'),
            'data_name_collides': good.replace('file STATE.BIN', 'file PLAN.TXT'),
            'data_hash_malformed': good.replace('785b0751', '785B0751'),
            'data_given_twice': good.replace('file STATE.BIN', 'file PAYLOAD.MAN'),
            'data_size_out_of_range': good.replace('size 1024', 'size 0'),
            'data_without_runner': good.replace('Q1N1-PAYLOAD.EFI --el2', 'Q1N1.EFI --el2'),
        }
        for reason, text in cases.items():
            with self.subTest(reason=reason):
                self.assertEqual(self.reason(text), reason)

    def test_text_that_differs_only_in_form_is_not_canonical(self):
        good = GOLDEN_PLAN_ONE
        cases = {
            'the data heading': good.replace('data files (', 'data files, ('),
            'a size with a leading zero': good.replace('size 1024', 'size 01024'),
            'an extra line in the section': good.replace('size 1024\r\n', 'size 1024\r\n  note\r\n'),
            'no blank line after the section': good.replace('\r\n\r\nHow it runs', '\r\nHow it runs'),
        }
        for what, text in cases.items():
            with self.subTest(what=what):
                self.assertNotEqual(text, good)
                self.assertEqual(self.reason(text), 'plan_text_not_canonical')

    def test_the_data_blocks_must_come_in_the_canonical_order(self):
        text = GOLDEN_PLAN_THREE
        first, second, end = text.index('  file DATA1.BIN'), text.index('  file DATA2.BIN'), text.index('  file STATE.BIN')
        swapped = text[:first] + text[second:end] + text[first:second] + text[end:]
        self.assertNotEqual(swapped, text)
        self.assertEqual(self.reason(swapped), 'plan_text_not_canonical')


