int probe_font_supported(char c)
{
    unsigned char u = (unsigned char)c;
    return (u >= FONT_FIRST && u <= FONT_LAST) || (u >= 'a' && u <= 'z') || u == '|';
}

const uint8_t *probe_font_glyph(char c)
{
    unsigned char u = (unsigned char)c;
    if (u >= 'a' && u <= 'z')
        u = (unsigned char)(u - 'a' + 'A');
    if (u >= FONT_FIRST && u <= FONT_LAST)
        return glyphs[u - FONT_FIRST];
    if (u == '|')
        return glyph_bar;
    return glyph_tofu;
}

int probe_font_is_tofu(const uint8_t *glyph)
{
    return glyph == glyph_tofu;
}
